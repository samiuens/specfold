// Bundles the CLI into the committed single file scripts/specfold.mjs.
import { chmodSync, readFileSync } from "node:fs";
import { build } from "esbuild";

const { version } = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));
const outfile = new URL("../../scripts/specfold.mjs", import.meta.url).pathname;

await build({
  entryPoints: [new URL("./src/bin.ts", import.meta.url).pathname],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20.19",
  define: { __SPECFOLD_VERSION__: JSON.stringify(version) },
  banner: { js: "#!/usr/bin/env node\n// Generated by tools/specfold/build.mjs. Do not edit." },
  legalComments: "eof",
  logLevel: "warning",
});
chmodSync(outfile, 0o755);
