#!/usr/bin/env node
// Kit repo only: writes docs/commands.md from the bundled CLI's --help output, or checks it with --check.
// Run from the kit root. see knowledge: /conventions/kit-docs.md
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const USAGE = "usage: node tools/specfold/docs.mjs [--check]";
const OUT = "docs/commands.md";

/** The CLI's commands with their summaries, as its top-level --help lists them. */
function commands(cli, root) {
  const help = execFileSync(process.execPath, [cli, "--help"], { cwd: root, encoding: "utf8" });
  const list = help.split("\n\n").find((part) => part.startsWith("Commands:")) ?? "";
  return list
    .split("\n")
    .slice(1)
    .map((line) => /^ {2}(\S+)\s+(.+)$/.exec(line))
    .filter(Boolean)
    .map(([, name, summary]) => ({ name, summary }));
}

/** The usage line `<command> --help` prints, without its `Usage: ` prefix. */
const usage = (cli, root, name) =>
  execFileSync(process.execPath, [cli, name, "--help"], { cwd: root, encoding: "utf8" })
    .trim()
    .replace(/^Usage: /, "");

export function render(root) {
  const cli = join(root, "scripts/specfold.mjs");
  const lines = [
    "# Command reference",
    "",
    "<!-- Generated by `node tools/specfold/docs.mjs` from the CLI's --help output; do not edit. -->",
    "",
    "Run every command from the repository root as `node scripts/specfold.mjs <command>`. `<command> --help` prints its usage line. Exit codes: 0 ok, 1 findings, 2 usage or environment error. Most commands take `--json` for machine-readable output.",
  ];
  for (const { name, summary } of commands(cli, root)) {
    lines.push("", `## ${name}`, "", `${summary[0].toUpperCase()}${summary.slice(1)}.`, "");
    lines.push("```sh", usage(cli, root, name), "```");
  }
  return `${lines.join("\n")}\n`;
}

export function docs(argv, root, out) {
  if (argv.length > 1 || (argv.length === 1 && argv[0] !== "--check")) {
    out.stderr(`docs: ${USAGE}\n`);
    return 2;
  }
  const text = render(root);
  const path = join(root, OUT);
  if (argv[0] === "--check") {
    if (existsSync(path) && readFileSync(path, "utf8") === text) return 0;
    out.stderr(`docs: ${OUT} is stale; run node tools/specfold/docs.mjs and commit it\n`);
    return 1;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  out.stdout(`docs: wrote ${OUT}\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = docs(process.argv.slice(2), process.cwd(), {
    stdout: (t) => process.stdout.write(t),
    stderr: (t) => process.stderr.write(t),
  });
}
