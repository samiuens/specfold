import { Document, isMap, Scalar, type YAMLSeq } from "yaml";
import { parseText } from "../bundle.ts";
import { EnvError } from "../errors.ts";
import { OMP_CONFIG } from "../omp/config.ts";

/** Role sources: Claude Code's subagent files. see knowledge: /references/omp.md */
export const CLAUDE_AGENTS = ".claude/agents";
/** omp's project roles, generated from `CLAUDE_AGENTS`. */
export const OMP_AGENTS = ".omp/agents";

/** omp subagents run headless and cannot ask the user, so omp plans in the main session. */
const SKIPPED = "planner";

const MARKER_START = "<!-- generated by specfold agents sync from ";
/** The first body line of a generated role; a file starting with it is the sync's own. */
export const marker = (name: string) => `${MARKER_START}${CLAUDE_AGENTS}/${name}.md; edit that file -->`;

const MODELS: Record<string, string> = { haiku: "@smol", sonnet: "@default", opus: "@slow" };
const TOOL_NAMES: Record<string, string> = {
  Read: "read",
  Grep: "grep",
  Glob: "glob",
  Bash: "bash",
  Write: "write",
  Edit: "edit",
  WebSearch: "web_search",
  AskUserQuestion: "ask",
  Agent: "task",
};

/** `table[key]` for the table's own keys only, so a value such as `toString` maps to nothing. */
const lookup = (table: Record<string, string>, key: string) =>
  Object.hasOwn(table, key) ? table[key] : undefined;

/** A Claude Code list value: a YAML list or a comma-separated string. */
function names(value: unknown): string[] {
  if (typeof value === "string")
    return value
      .split(",")
      .map((s) => s.trim())
      .filter((s) => s !== "");
  return Array.isArray(value) ? value.filter((v): v is string => typeof v === "string") : [];
}

/**
 * Frontmatter read line by line: top-level `key: value` pairs, `[a, b]` and `- item` lists. Claude Code accepts
 * blocks that are not strict YAML, such as a description holding `: `, so a role is not refused for that.
 */
function looseFrontmatter(lines: string[]): Record<string, unknown> {
  const data: Record<string, unknown> = {};
  let list: string[] | undefined;
  for (const line of lines) {
    const item = /^\s+-\s+(.*)$/.exec(line);
    if (item) {
      list?.push((item[1] as string).trim());
      continue;
    }
    const pair = /^([A-Za-z][\w-]*):(?:\s+(.*))?$/.exec(line);
    list = undefined;
    if (!pair) continue;
    const key = pair[1] as string;
    const value = (pair[2] ?? "").trim();
    const flow = /^\[(.*)\]$/.exec(value);
    if (value === "") {
      list = [];
      data[key] = list;
    } else data[key] = flow ? names(flow[1]) : value.replace(/^(["'])(.*)\1$/, "$2");
  }
  return data;
}

/** The frontmatter of a Claude Code agent file; a block that is not valid YAML is read with `looseFrontmatter`. */
function agentFrontmatter(rel: string, source: string): { data: Record<string, unknown>; body: string } {
  const parsed = parseText(rel, source);
  if (!parsed.frontmatterError)
    return { data: (parsed.frontmatter?.data ?? {}) as Record<string, unknown>, body: parsed.body };
  const lines = source.replace(/\r\n/g, "\n").split("\n");
  const end = lines.findIndex((line, i) => i > 0 && (line === "---" || line === "..."));
  if (end === -1) throw new EnvError(`${rel}: ${parsed.frontmatterError.message}`);
  return { data: looseFrontmatter(lines.slice(1, end)), body: parsed.body };
}

/** The omp role text for the Claude Code agent `name`, from the source file's text. */
export function renderRole(name: string, source: string): string {
  const rel = `${CLAUDE_AGENTS}/${name}.md`;
  const { data, body } = agentFrontmatter(rel, source);
  const fields: Record<string, unknown> = {};
  if (data.name !== undefined) fields.name = data.name;
  if (data.description !== undefined) fields.description = data.description;
  const model = typeof data.model === "string" ? lookup(MODELS, data.model) : undefined;
  if (model) fields.model = model;
  if (data.effort !== undefined) fields["thinking-level"] = data.effort;
  if (data.tools !== undefined)
    fields.tools = [...new Set(names(data.tools).flatMap((t) => lookup(TOOL_NAMES, t) ?? []))];
  if (names(data.disallowedTools).includes("Agent")) fields.spawns = "";
  if (data.skills !== undefined) fields["autoload-skills"] = names(data.skills);

  const doc = new Document(fields);
  if (model) (doc.get("model", true) as Scalar).type = Scalar.QUOTE_DOUBLE;
  for (const key of ["tools", "autoload-skills"]) {
    const seq = doc.get(key, true) as YAMLSeq | undefined;
    if (seq) seq.flow = true;
  }
  const front =
    Object.keys(fields).length > 0 ? doc.toString({ lineWidth: 0, flowCollectionPadding: false }) : "";
  return `---\n${front}---\n${marker(name)}\n${body}`;
}

/** Whether a role file's body starts with the generated line. */
export const isOwnRole = (text: string): boolean => parseText("", text).body.startsWith(MARKER_START);

export type RoleAction = "write" | "rewrite" | "remove" | "kept";

export interface PlannedRole {
  /** Repository-relative path of the role file. */
  path: string;
  action: RoleAction;
  /** The source file for write and rewrite, otherwise null. */
  target: string | null;
  /** The text to write for write and rewrite. */
  text?: string;
}

/**
 * Compares the role files with their sources and returns the actions that bring them in line. `sources` and
 * `roles` map a name to file text; `listed` is false when `tools` has no `omp`, which removes every own role.
 */
export function planRoles(
  sources: Record<string, string>,
  roles: Record<string, string>,
  listed: boolean,
): PlannedRole[] {
  const out: PlannedRole[] = [];
  const wanted = listed ? Object.keys(sources).filter((n) => n !== SKIPPED) : [];
  for (const name of wanted.sort()) {
    const path = `${OMP_AGENTS}/${name}.md`;
    const target = `${CLAUDE_AGENTS}/${name}.md`;
    const text = renderRole(name, sources[name] as string);
    const current = roles[name];
    if (current === undefined) out.push({ path, action: "write", target, text });
    else if (!isOwnRole(current)) out.push({ path, action: "kept", target: null });
    else if (current !== text) out.push({ path, action: "rewrite", target, text });
  }
  for (const name of Object.keys(roles).sort()) {
    if (wanted.includes(name) || !isOwnRole(roles[name] as string)) continue;
    out.push({ path: `${OMP_AGENTS}/${name}.md`, action: "remove", target: null });
  }
  return out;
}

export interface PlannedSetting {
  path: typeof OMP_CONFIG;
  action: "set";
  /** The key and its new value, such as `task.maxRecursionDepth: 1`. */
  target: string;
}

/** The `task` keys Specfold owns in `.omp/config.yml`; sf-apply merges each isolated task's branch itself. */
const TASK_SETTINGS: [string[], number | boolean | string][] = [
  [["task", "maxRecursionDepth"], 1],
  [["task", "isolation", "enabled"], true],
  [["task", "isolation", "merge"], "branch"],
  [["task", "isolation", "apply"], false],
];

/** Sets the owned task keys in the parsed `.omp/config.yml`, keeping every other key; returns the keys it changed. */
export function setTaskSettings(doc: Document): PlannedSetting[] {
  const out: PlannedSetting[] = [];
  for (const [keys, value] of TASK_SETTINGS) {
    if (doc.getIn(keys) === value) continue;
    for (let i = 1; i < keys.length; i++) {
      const parent = doc.getIn(keys.slice(0, i), true);
      if (parent !== undefined && parent !== null && !isMap(parent))
        throw new EnvError(`${OMP_CONFIG}: '${keys.slice(0, i).join(".")}' is not a mapping`);
    }
    doc.setIn(keys, value);
    out.push({ path: OMP_CONFIG, action: "set", target: `${keys.join(".")}: ${value}` });
  }
  return out;
}
